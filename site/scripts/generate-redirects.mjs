/**
 * Generate Cloudflare Pages redirect rules from the WordPress URL map.
 *
 * Input : src/data/redirects.json  (produced by tools/export_content.py)
 * Output: public/_redirects
 *
 * Run with:  npm run redirects
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, '..');

const map = JSON.parse(
  await readFile(path.join(siteRoot, 'src', 'data', 'redirects.json'), 'utf-8'),
);

/**
 * Fase 10 audit gate (../audit/posts.json): duplicate-topic posts 301 to
 * their canonical sibling. Keeping them out of the listing/sitemap is the
 * redirectTo field in frontmatter; this closes the URL itself.
 */
const audit = JSON.parse(
  await readFile(path.join(siteRoot, '..', 'audit', 'posts.json'), 'utf-8'),
);
const dedup = {};
for (const [slug, d] of Object.entries(audit.decisions ?? {})) {
  if (d.action === 'redirect' && d.to) dedup[`/blog/${slug}/`] = d.to;
}

/**
 * Old WordPress pages that have no 1:1 equivalent.
 *
 * Only additions belong here. `/agentvalley.html` used to be one of them and
 * pointed at /agent/ — which silently overwrote the correct /agent/alt/ that
 * the export had already worked out, because EXTRA was merged last. It is not
 * an addition, it is a duplicate of a rule the map already answers.
 */
const EXTRA = {
  '/blog.html': '/blog/',
  '/blog-2.html': '/blog/',
  '/valley-city.html': '/',
  '/kebijakan-privasi.html': '/privacy/',
  '/terimakasih.html': '/thank-you/',
  '/nup.html': '/nup/',
  '/sale.html': '/sale/',
  '/agent.html': '/agent/',
  '/skagent.html': '/agent/terms/',
  '/index.php': '/',
  // The enquiry form lives on the homepage.
  '/contact.html': '/',
};

const lines = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand.',
  '# Cloudflare Pages redirect rules: <from> <to> <status>',
  '',
];

/* The exported map is the truth; EXTRA only fills gaps it left. Merging the
   other way round is what produced the wrong /agentvalley.html target. The
   audit dedup map is applied last — it is a deliberate, reviewed decision
   over the mechanical WordPress export. */
const all = { ...EXTRA, ...map, ...dedup };
for (const [from, to] of Object.entries(all)) {
  if (!from || from === to) continue;
  lines.push(`${from}  ${to}  301`);
}

// Anything left in the old /<slug>.html shape that we did not map explicitly.
lines.push('');
lines.push('# Catch-all for the old /<slug>.html shape.');
lines.push('/*.html  /blog/:splat  301');

await writeFile(path.join(siteRoot, 'public', '_redirects'), lines.join('\n') + '\n');

console.log(`wrote public/_redirects — ${Object.keys(all).length} explicit rules (${Object.keys(dedup).length} from the Fase 10 audit)`);
